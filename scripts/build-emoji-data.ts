// Rewrites the emoji list Redhot ships. Run it by hand after a new Unicode release:
// node scripts/build-emoji-data.ts
import { writeFile } from "node:fs/promises";
import { join } from "node:path";

const EMOJI_VERSION = "17.0";
const CLDR_VERSION = "48.0.0";
const EMOJI_TEST_URL = `https://unicode.org/Public/${EMOJI_VERSION}.0/emoji/emoji-test.txt`;
const ANNOTATIONS_URL = `https://raw.githubusercontent.com/unicode-org/cldr-json/${CLDR_VERSION}/cldr-json/cldr-annotations-full/annotations/en/annotations.json`;
const OUTPUT_PATH = join(import.meta.dirname, "../src/redhot-apps/redhot-emoji/data.ts");

const VARIATION_SELECTOR = "️";
const FIELD_SEPARATOR = "|";
const FIRST_NON_ASCII = 0x80;
const FULLY_QUALIFIED_LINE = /^[0-9A-F ]+; fully-qualified\s+# (\S+) E[\d.]+ (.+)$/u;
// Skin tones and hair colours multiply the list several times over for very little.
const TONE_OR_HAIR = /[\u{1F3FB}-\u{1F3FF}\u{1F9B0}-\u{1F9B3}]/u;

// Useful on a Mac, and missing from Unicode's annotations.
const EXTRA_SYMBOLS: readonly (readonly [string, string, ...string[]])[] = [
  ["⌘", "command key", "cmd", "mac"],
  ["⌥", "option key", "alt", "mac"],
  ["⌃", "control key", "ctrl", "mac"],
  ["⌫", "delete key", "backspace", "mac"],
  ["⌦", "forward delete key", "mac"],
  ["⎋", "escape key", "esc", "mac"],
  ["⏎", "return key", "enter", "mac"],
  ["✓", "check mark", "tick", "done"],
  ["✗", "ballot x", "cross", "no"],
  ["π", "pi", "greek", "math"],
];

interface Annotation {
  default: string[];
  tts: string[];
}

interface Row {
  character: string;
  name: string;
  keywords: readonly string[];
}

const fetchText = async (url: string): Promise<string> => {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status}`);
  }
  return response.text();
};

const toAnnotationKey = (character: string): string => character.replaceAll(VARIATION_SELECTOR, "");

const isListed = (character: string): boolean =>
  !TONE_OR_HAIR.test(character) && (character.codePointAt(0) ?? 0) >= FIRST_NON_ASCII;

// Words already in the name would only make the file bigger, because the name is searched too.
const toKeywords = (name: string, keywords: readonly string[] = []): string[] => {
  const lowerName = name.toLowerCase();
  return keywords
    .map((keyword) => keyword.toLowerCase())
    .filter((keyword) => !lowerName.includes(keyword));
};

const toEmojiRows = (emojiTest: string, annotations: Readonly<Record<string, Annotation>>): Row[] =>
  emojiTest.split("\n").flatMap((line) => {
    const [, character, name] = FULLY_QUALIFIED_LINE.exec(line) ?? [];
    if (character === undefined || name === undefined || !isListed(character)) {
      return [];
    }
    const keywords = annotations[toAnnotationKey(character)]?.default;
    return [{ character, name, keywords: toKeywords(name, keywords) }];
  });

const toSymbolRows = (
  annotations: Readonly<Record<string, Annotation>>,
  emojiKeys: ReadonlySet<string>,
): Row[] => {
  const annotated = Object.entries(annotations).flatMap(([character, annotation]) => {
    const name = annotation.tts[0]?.toLowerCase();
    if (name === undefined || emojiKeys.has(character) || !isListed(character)) {
      return [];
    }
    return [{ character, name, keywords: toKeywords(name, annotation.default) }];
  });
  const extras = EXTRA_SYMBOLS.map(([character, name, ...keywords]) => ({
    character,
    name,
    keywords,
  }));
  return [...annotated, ...extras];
};

const toLine = ({ character, name, keywords }: Row): string =>
  [character, name, ...keywords].join(FIELD_SEPARATOR);

const [emojiTest, annotationsFile] = await Promise.all([
  fetchText(EMOJI_TEST_URL),
  fetchText(ANNOTATIONS_URL),
]);
const { annotations } = (
  JSON.parse(annotationsFile) as { annotations: { annotations: Record<string, Annotation> } }
).annotations;

const emojiRows = toEmojiRows(emojiTest, annotations);
const emojiKeys = new Set(emojiRows.map(({ character }) => toAnnotationKey(character)));
const rows = [...emojiRows, ...toSymbolRows(annotations, emojiKeys)];

await writeFile(
  OUTPUT_PATH,
  `// Generated by scripts/build-emoji-data.ts, so change that instead.
// From Unicode's emoji-test.txt ${EMOJI_VERSION} and CLDR ${CLDR_VERSION} English annotations.
// © Unicode, Inc. Licence: https://www.unicode.org/license.txt
export const EMOJI_DATA = \`${rows.map(toLine).join("\n")}\`;
`,
);
process.stdout.write(`Wrote ${rows.length} rows to ${OUTPUT_PATH}\n`);
